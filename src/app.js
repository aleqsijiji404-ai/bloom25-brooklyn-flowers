window.App = function App() {
  const [lang, setLang] = React.useState('ka'); // 'ka' | 'en'
  const [theme, setTheme] = React.useState('dark'); // 'dark' | 'light'
  const [products, setProducts] = React.useState([]);
  const [cartItems, setCartItems] = React.useState([]);
  const [activeCategory, setActiveCategory] = React.useState('All');
  
  // Modals & Drawers
  const [selectedProduct, setSelectedProduct] = React.useState(null);
  const [isCartOpen, setIsCartOpen] = React.useState(false);
  const [isAdminOpen, setIsAdminOpen] = React.useState(false);
  const [completedOrder, setCompletedOrder] = React.useState(null);
  const [toastMsg, setToastMsg] = React.useState('');

  const t = translations[lang];

  // Apply Theme Attribute
  React.useEffect(() => {
    document.documentElement.setAttribute('data-theme', theme);
  }, [theme]);

  // Load Inventory from LocalStorage or Fetch default JSON
  React.useEffect(() => {
    const saved = localStorage.getItem('bloom25_products');
    if (saved) {
      try {
        setProducts(JSON.parse(saved));
      } catch (e) {
        console.error("Failed to parse saved products", e);
      }
    } else {
      fetch('./src/data/products.json')
        .then(res => res.json())
        .then(data => {
          setProducts(data);
          localStorage.setItem('bloom25_products', JSON.stringify(data));
        })
        .catch(err => console.error("Error loading products.json", err));
    }
  }, []);

  const showToast = (msg) => {
    setToastMsg(msg);
    setTimeout(() => setToastMsg(''), 3000);
  };

  // Cart Operations
  const handleAddToCart = (product, size = 'standard', qty = 1) => {
    const existingIndex = cartItems.findIndex(i => i.id === product.id && i.size === size);
    let updatedCart = [...cartItems];

    if (existingIndex > -1) {
      updatedCart[existingIndex].quantity += qty;
    } else {
      const extraPrice = size === 'deluxe' ? 35 : size === 'grand' ? 70 : 0;
      updatedCart.push({
        ...product,
        size,
        price: product.price + extraPrice,
        quantity: qty
      });
    }

    setCartItems(updatedCart);
    showToast(lang === 'ka' ? '🌸 ყვავილები დაემატა კალათაში!' : '🌸 Added to cart!');
  };

  const handleUpdateQty = (index, newQty) => {
    if (newQty <= 0) {
      handleRemoveItem(index);
    } else {
      const updated = [...cartItems];
      updated[index].quantity = newQty;
      setCartItems(updated);
    }
  };

  const handleRemoveItem = (index) => {
    const updated = cartItems.filter((_, i) => i !== index);
    setCartItems(updated);
  };

  // Product Admin Operations
  const handleAddProduct = (newProduct) => {
    const updated = [newProduct, ...products];
    setProducts(updated);
    localStorage.setItem('bloom25_products', JSON.stringify(updated));
    showToast(lang === 'ka' ? '✅ ახალი ყვავილი დაემატა!' : '✅ New product added!');
  };

  const handleUpdateProduct = (updatedProduct) => {
    const updated = products.map(p => p.id === updatedProduct.id ? updatedProduct : p);
    setProducts(updated);
    localStorage.setItem('bloom25_products', JSON.stringify(updated));
    showToast(lang === 'ka' ? '✅ პროდუქტი განახლდა!' : '✅ Product updated!');
  };

  const handleDeleteProduct = (id) => {
    if (window.confirm(lang === 'ka' ? 'ნამდვილად გსურთ ამ ყვავილის წაშლა?' : 'Are you sure you want to delete this product?')) {
      const updated = products.filter(p => p.id !== id);
      setProducts(updated);
      localStorage.setItem('bloom25_products', JSON.stringify(updated));
      showToast(lang === 'ka' ? '🗑️ პროდუქტი წაიშალა' : '🗑️ Product removed');
    }
  };

  const handleResetProducts = () => {
    if (window.confirm(lang === 'ka' ? 'ნამდვილად გსურთ საწყის კატალოგზე დაბრუნება?' : 'Reset catalog to default items?')) {
      fetch('./src/data/products.json')
        .then(res => res.json())
        .then(data => {
          setProducts(data);
          localStorage.setItem('bloom25_products', JSON.stringify(data));
          showToast(lang === 'ka' ? '🔄 კატალოგი აღდგა' : '🔄 Catalog reset');
        });
    }
  };

  const handleCompleteOrder = (orderData) => {
    setCompletedOrder(orderData);
    setCartItems([]);
    setIsCartOpen(false);
  };

  return (
    <div style={{ minHeight: '100vh', display: 'flex', flexDirection: 'column' }}>
      {/* Header */}
      <window.Header
        lang={lang}
        setLang={setLang}
        theme={theme}
        setTheme={setTheme}
        cartCount={cartItems.reduce((sum, item) => sum + item.quantity, 0)}
        onOpenCart={() => setIsCartOpen(true)}
        onOpenAdmin={() => setIsAdminOpen(true)}
        t={t}
      />

      {/* Main Content */}
      <main style={{ flex: 1 }}>
        <window.Hero
          t={t}
          onScrollToCatalog={() => document.getElementById('catalog')?.scrollIntoView({ behavior: 'smooth' })}
          onScrollToBuilder={() => document.getElementById('builder')?.scrollIntoView({ behavior: 'smooth' })}
        />

        <window.BentoGrid
          t={t}
          onSelectCategory={(cat) => {
            setActiveCategory(cat);
            document.getElementById('catalog')?.scrollIntoView({ behavior: 'smooth' });
          }}
        />

        <window.Catalog
          products={products}
          lang={lang}
          t={t}
          onAddToCart={handleAddToCart}
          onSelectProduct={(p) => setSelectedProduct(p)}
          activeCategory={activeCategory}
          setActiveCategory={setActiveCategory}
        />

        <window.BouquetBuilder
          t={t}
          lang={lang}
          onAddToCart={(customItem) => {
            handleAddToCart(customItem, 'custom', 1);
            setIsCartOpen(true);
          }}
        />
      </main>

      {/* Footer */}
      <window.Footer lang={lang} t={t} />

      {/* Modals & Drawers */}
      {selectedProduct && (
        <window.ProductModal
          product={selectedProduct}
          lang={lang}
          t={t}
          onClose={() => setSelectedProduct(null)}
          onAddToCart={handleAddToCart}
        />
      )}

      <window.CartDrawer
        isOpen={isCartOpen}
        onClose={() => setIsCartOpen(false)}
        cartItems={cartItems}
        onUpdateQty={handleUpdateQty}
        onRemoveItem={handleRemoveItem}
        lang={lang}
        t={t}
        onCompleteOrder={handleCompleteOrder}
      />

      <window.AdminModal
        isOpen={isAdminOpen}
        onClose={() => setIsAdminOpen(false)}
        products={products}
        onAddProduct={handleAddProduct}
        onUpdateProduct={handleUpdateProduct}
        onDeleteProduct={handleDeleteProduct}
        onResetProducts={handleResetProducts}
        lang={lang}
        t={t}
      />

      {completedOrder && (
        <window.OrderReceiptModal
          order={completedOrder}
          onClose={() => setCompletedOrder(null)}
          lang={lang}
          t={t}
        />
      )}

      {/* Toast Notification */}
      {toastMsg && (
        <div style={{
          position: 'fixed',
          bottom: '24px',
          right: '24px',
          background: 'linear-gradient(135deg, #1B4D3E 0%, #0D261F 100%)',
          color: '#8FFFE1',
          border: '1px solid #8FFFE1',
          padding: '14px 24px',
          borderRadius: 'var(--radius-full)',
          fontWeight: '700',
          fontSize: '0.9rem',
          zIndex: 9999,
          boxShadow: '0 10px 30px rgba(0,0,0,0.5)',
          animation: 'fadeIn 0.3s ease-out'
        }}>
          {toastMsg}
        </div>
      )}
    </div>
  );
};
